package com.kaya.common;

/**
 * Expected business failure. The code is returned in the response envelope;
 * HTTP status is derived by {@link GlobalExceptionHandler}.
 */
public class BusinessException extends RuntimeException {

    private final int code;

    public BusinessException(int code, String message) {
        super(message);
        this.code = code;
    }

    public BusinessException(int code, String message, Throwable cause) {
        super(message, cause);
        this.code = code;
    }

    public int getCode() {
        return code;
    }
}
